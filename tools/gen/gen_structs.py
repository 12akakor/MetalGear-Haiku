"""Generates src/game/Structures.h from constants/structures.asm and
constants/Enums.asm of the disassembly: field offsets of the game's data
structures (actors, doors, sound channels...) and the named constants.

    gen_structs.py <disassembly dir> <src/game/Structures.h>
"""
import re
import sys

root, out = sys.argv[1:3]
lines = ['''/*
 * Copyright 2026, Akakor.
 * All rights reserved. Distributed under the terms of the MIT License.
 */
#ifndef MG_STRUCTURES_H
#define MG_STRUCTURES_H


// Generated by tools/gen/gen_structs.py, do not edit.
// Field offsets of the game's structures and its named constants, as in
// constants/structures.asm and constants/Enums.asm of the disassembly.

''']
struct = None
offset = 0
for raw in open(root + "/constants/structures.asm", encoding="latin-1"):
	line = raw.split(";")[0].rstrip()
	m = re.match(r"\s*STRUCT\s+(\w+)", line)
	if m:
		struct, offset = m.group(1), 0
		lines.append("namespace %s {\nenum {\n" % struct)
		continue
	if re.match(r"\s*ENDS", line):
		lines.append("\tkSize = %d\n};\n}\n\n" % offset)
		struct = None
		continue
	m = re.match(r"^(\w+):\s*(BYTE|WORD|DWORD|BLOCK\s+\d+|ds\s+\d+)?", line, re.I)
	if struct and m:
		lines.append("\t%s = 0x%02x,\n" % (m.group(1), offset))
		kind = (m.group(2) or "BYTE").upper()
		if kind == "BYTE":
			offset += 1
		elif kind == "WORD":
			offset += 2
		elif kind == "DWORD":
			offset += 4
		else:
			offset += int(kind.split()[1])
lines.append("\n// Constants\n")
seen = set()
for raw in open(root + "/constants/Enums.asm", encoding="latin-1"):
	line = raw.split(";")[0].rstrip()
	m = re.match(r"^(\w+):?\s+equ\s+([0-9A-Fa-f]+h|[0-9]+|#[0-9A-Fa-f]+|0x[0-9A-Fa-f]+)\s*$", line, re.I)
	if not m or m.group(1) in seen:
		continue
	seen.add(m.group(1))
	v = m.group(2)
	if v.lower().endswith("h"):
		value = int(v[:-1], 16)
	elif v.startswith("#"):
		value = int(v[1:], 16)
	else:
		value = int(v, 0)
	lines.append("constexpr int %s = 0x%02x;\n" % (m.group(1), value))
lines.append("\n\n#endif	// MG_STRUCTURES_H\n")
open(out, "w").write("".join(lines))
print("%d constants" % len(seen))
