"""Generates tests/RomBanks.h: for every ROM symbol, the first bank of the
source file (Banks0123.asm = 0, Banks456.asm = 4, ...) it is in. With the
address this gives the bank: tests use it to recognise when the original
enters a routine.

    gen_banks.py <disassembly dir> <src/game/RomSymbols.h> <tests/RomBanks.h>
"""
import os
import re
import sys

root, symh, out = sys.argv[1:4]
names = re.findall(r"^\t(\w+),$", open(symh).read(), re.M)
base_of = {}


def walk(path, base):
	for raw in open(path, encoding="latin-1"):
		line = raw.split(";")[0]
		m = re.match(r'\s*include\s+"?([^"\s]+)"?', line, re.I)
		if m:
			inc = os.path.join(root, m.group(1))
			if not os.path.exists(inc):
				# nested includes are relative to the including file
				inc = os.path.join(os.path.dirname(path), m.group(1))
			if os.path.exists(inc):
				b = base
				fm = re.match(r"Banks([0-9A-F])", m.group(1))
				if fm:
					b = int(fm.group(1), 16)
				walk(inc, b)
			continue
		m = re.match(r"^([A-Za-z_]\w*):", line)
		if m and base is not None:
			base_of.setdefault(m.group(1), base)


walk(os.path.join(root, "MetalGear.asm"), None)
with open(out, "w") as f:
	f.write("""/*
 * Copyright 2026, Akakor.
 * All rights reserved. Distributed under the terms of the MIT License.
 */
#ifndef MG_ROM_BANKS_H
#define MG_ROM_BANKS_H


// Generated by tools/gen/gen_banks.py, do not edit.

#include "../src/game/RomSymbols.h"


// The bank a ROM symbol is in (-1: unknown).
static inline int
RoutineBank(sym::Id id)
{
	static const signed char kBase[sym::Count] = {
""")
	vals = [base_of.get(n, -1) for n in names]
	for i in range(0, len(vals), 16):
		f.write("\t\t" + ", ".join("%d" % v for v in vals[i:i + 16]) + ",\n")
	f.write("""	};
	int base = kBase[id];
	uint16_t address = RomSymbol(id);
	if (base < 0 || address == 0xffff)
		return -1;
	if (base == 0)
		return address < 0x6000 ? 0 : 1 + (address - 0x6000) / 0x2000;
	return base + (address - 0x6000) / 0x2000;
}


#endif	// MG_ROM_BANKS_H
""")
print("%d of %d symbols placed" % (sum(v >= 0 for v in vals), len(vals)))
