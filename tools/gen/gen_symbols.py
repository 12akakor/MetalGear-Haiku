#!/usr/bin/env python3
"""
Generates src/game/rom_symbols.{h,cpp}: the addresses of the ROM symbols of
the disassembly for every supported ROM version, so the C++ code can find
data in each version.

  gen_symbols.py <english .sym> <japanese .sym> <output dir>

Build the .sym files with: sjasm -s MetalGear.asm MetalGear.rom
(JAPANESE equ 0 for English, 1 for Japanese).
"""
import re, sys

def load(path):
    d = {}
    for line in open(path):
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*): equ ([0-9A-Fa-f]+)h', line)
        if m:
            v = int(m.group(2), 16)
            if 0x4000 <= v < 0xc000:		# ROM addresses only
                d[m.group(1)] = v
    return d

en, jp = load(sys.argv[1]), load(sys.argv[2])
names = sorted(set(en) | set(jp))
out = sys.argv[3]
with open(out + '/RomSymbols.h', 'w') as h:
    h.write('''/*
 * Copyright 2026, Akakor.
 * All rights reserved. Distributed under the terms of the MIT License.
 */
#ifndef MG_ROM_SYMBOLS_H
#define MG_ROM_SYMBOLS_H


// Generated by tools/gen/gen_symbols.py, do not edit.
// ROM addresses of the disassembly symbols per ROM version.

#include <stdint.h>


namespace sym {
enum Id {
''')
    for n in names:
        h.write('\t%s,\n' % n)
    h.write('''\tCount
};
}

/* Address of a symbol in the loaded ROM version; 0xffff if that version
   does not have it. */
uint16_t RomSymbol(sym::Id id);


#endif	// MG_ROM_SYMBOLS_H
''')
with open(out + '/RomSymbols.cpp', 'w') as c:
    c.write('/*\n * Copyright 2026, Akakor.\n * All rights reserved. Distributed under the terms of the MIT License.\n */\n\n\n// Generated by tools/gen/gen_symbols.py, do not edit.\n\n')
    c.write('#include "RomSymbols.h"\n\n#include "GameData.h"\n\n\n')
    for tag, d in (('English', en), ('Japanese', jp)):
        c.write('static const uint16_t k%s[sym::Count] = {\n' % tag)
        for i in range(0, len(names), 8):
            c.write('\t' + ', '.join('0x%04x' % d.get(n, 0xffff) for n in names[i:i+8]) + ',\n')
        c.write('};\n\n')
    c.write('''uint16_t
RomSymbol(sym::Id id)
{
	const uint16_t* table = LoadedRomVersion() == kRomJapanese ? kJapanese : kEnglish;
	return table[id];
}
''')
print('%d symbols (%d English, %d Japanese)' % (len(names), len(en), len(jp)))

# RAM variables: the same in every version
def load_ram(path):
    d = {}
    for line in open(path):
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*): equ ([0-9A-Fa-f]+)h', line)
        if m and int(m.group(2), 16) >= 0xc000:
            d[m.group(1)] = int(m.group(2), 16)
    return d
ren, rjp = load_ram(sys.argv[1]), load_ram(sys.argv[2])
assert ren == rjp, 'RAM layout differs between versions'
with open(out + '/RamSymbols.h', 'w') as h:
    h.write('''/*
 * Copyright 2026, Akakor.
 * All rights reserved. Distributed under the terms of the MIT License.
 */
#ifndef MG_RAM_SYMBOLS_H
#define MG_RAM_SYMBOLS_H


// Generated by tools/gen/gen_symbols.py, do not edit.
// Addresses of the game variables (the same in every ROM version).

#include <stdint.h>


namespace var {

''')
    for n in sorted(ren):
        h.write('constexpr uint16_t %s = 0x%04x;\n' % (n, ren[n]))
    h.write('\n}\n\n\n#endif\t// MG_RAM_SYMBOLS_H\n')
print('%d RAM symbols' % len(ren))
