"""Generates src/game/RomBlockCrc.h: the CRC32 of every 256 byte block of
the two reference ROMs (English, Japanese). Only checksums, no game data.
Modified ROMs (translations, SCC versions) are recognised by how many
blocks they share with a reference.

    gen_blockcrc.py <English .rom> <Japanese .rom> <src/game/RomBlockCrc.h>
"""
import sys
import zlib

en, jp, out = sys.argv[1:4]
roms = [open(en, "rb").read(), open(jp, "rb").read()]
with open(out, "w") as f:
	f.write("""/*
 * Copyright 2026, Akakor.
 * All rights reserved. Distributed under the terms of the MIT License.
 */
#ifndef MG_ROM_BLOCK_CRC_H
#define MG_ROM_BLOCK_CRC_H


// Generated by tools/gen/gen_blockcrc.py, do not edit.

#include <stdint.h>


// CRC32 of every 256 byte block: [0] English, [1] Japanese; 0 for a block
// of one repeated byte (not counted, any ROM can have those).
static const uint32_t kBlockCrc[2][512] = {
""")
	for rom in roms:
		f.write("\t{\n")
		vals = []
		for i in range(0, 0x20000, 256):
			block = rom[i:i + 256]
			vals.append(0 if len(set(block)) == 1 else zlib.crc32(block) & 0xffffffff)
		for i in range(0, 512, 6):
			f.write("\t\t" + ", ".join("0x%08x" % v for v in vals[i:i + 6]) + ",\n")
		f.write("\t},\n")
	f.write("""};


#endif	// MG_ROM_BLOCK_CRC_H
""")
